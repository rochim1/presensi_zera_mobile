"""Rebuild the reviewed legacy UI bridge after flutter gen-l10n.

ARB files remain the source of translations. The frozen audit supplies aliases
for the original UI wording; additional short labels live in supplemental_ui.json.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
L10N = ROOT / 'lib/l10n'
arb = json.loads((L10N / 'app_id.arb').read_text(encoding='utf-8'))
generated = (L10N / 'generated/app_localizations.dart').read_text(encoding='utf-8')
aliases = json.loads((L10N / 'legacy_ui_aliases.json').read_text(encoding='utf-8'))

def quote(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

exact, patterns = [], []
seen_exact = set()
for key, value in arb.items():
    if key.startswith('@') or not isinstance(value, str) or key == 'signInAction' or key.startswith('relative'):
        continue
    source = aliases.get(key, value)
    source = re.sub(r'\{\{(par\d+)\}\}', r'{\1}', source)
    source = source.replace('${e.message}', '{message}').replace('$message', '{message}')
    captures = list(re.finditer(r'\{(\w+)\}', source))
    method = re.search(r'  String '+re.escape(key)+r'\((.*?)\);', generated, re.S)
    if not captures or method is None:
        if source in seen_exact:
            continue
        seen_exact.add(source)
        exact.append(f'  {quote(source)}: (l) => l.{key},')
        continue
    params = re.findall(r'String (\w+)', method.group(1))
    names = [m.group(1) for m in captures]
    pattern, last = '^', 0
    for match in captures:
        pattern += re.escape(source[last:match.start()]) + '(.*?)'
        last = match.end()
    pattern += re.escape(source[last:]) + '$'
    args = ', '.join(f'v[{names.index(p)}]' for p in params)
    patterns.append((len(source)-sum(len(m.group()) for m in captures), f'  _HrPattern({quote(pattern)}, (l, v) => l.{key}({args})), '))
patterns.sort(key=lambda p: -p[0])
result = '''// Generated by scripts/build_hr_translation_lookup.py. UI copy only.
import 'generated/app_localizations.dart';
typedef _HrValue = String Function(AppLocalizations);
class _HrPattern {
  _HrPattern(String source, this.render) : pattern = RegExp(source, dotAll: true);
  final RegExp pattern;
  final String Function(AppLocalizations, List<String>) render;
}
final Map<String, _HrValue> _exact = {
'''+ '\n'.join(exact)+ '\n};\nfinal List<_HrPattern> _patterns = [\n'+ '\n'.join(p[1] for p in patterns)+'''
];
String translateHrText(String source, AppLocalizations locale) {
  final exact = _exact[source];
  if (exact != null) return exact(locale);
  for (final entry in _patterns) {
    final match = entry.pattern.firstMatch(source);
    if (match != null) {
      return entry.render(locale, [for (var i=1;i<=match.groupCount;i++) match.group(i) ?? '']);
    }
  }
  return source;
}
'''
(L10N / 'hr_translation_lookup.dart').write_text(result, encoding='utf-8')
print(f'{len(exact)} exact UI labels; {len(patterns)} parameterized UI templates.')
